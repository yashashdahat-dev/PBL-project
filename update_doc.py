"""
update_doc.py
=============
Generates comprehensive Evaluation_Graphs_List.md with clickable links for all 77 graphs.
"""

import os

base_dir = r"d:\ff\evaluation_graphs_all_77"
categories = [
    ("Communication_Performance", "1. Communication Performance Graphs (Graphs 1-9)"),
    ("Mission_Performance", "2. Mission Performance Graphs (Graphs 10-18)"),
    ("Scalability_Graphs", "3. Scalability Graphs (Graphs 19-30)"),
    ("Convergence_Graphs", "4. Convergence Graphs (Graphs 31-36)"),
    ("Resource_Allocation_Graphs", "5. Resource Allocation Graphs (Graphs 37-42)"),
    ("Robustness_Graphs", "6. Robustness Graphs (Graphs 43-48)"),
    ("Mission_Specific", "7. Mission-Specific Comparison (Graphs 49-56)"),
    ("AI_Specific_Graphs", "8. AI-Specific Graphs (Graphs 57-62)"),
    ("Complexity_Analysis", "9. Complexity Analysis (Graphs 63-67)"),
    ("Statistical_Evaluation", "10. Statistical Evaluation (Graphs 68-77)")
]

lines = [
    "# Comprehensive Evaluation Graphs Catalog for I-MACSI (All 77 Graphs)",
    "",
    "This document catalogs all **77 high-resolution (300 DPI)** empirical evaluation result graphs for **I-MACSI** (Intent-Aware Multi-Agent Cognitive Swarm Intelligence) compared against **9 state-of-the-art benchmarks**.",
    "",
    "- [Interactive Visual Gallery](file:///d:/ff/evaluation_graphs_all_77/index.html) *(Filter by category, search by metric, and view high-res popups)*",
    "",
    "## Algorithms Compared (10 Total)",
    "1. **I-MACSI (Proposed)** - Intent-Aware Multi-Agent Cognitive Swarm Intelligence with 8D Intent & Dynamic Q-Shaping",
    "2. **MADRL** - Multi-Agent Deep Reinforcement Learning (MAPPO/MADDPG baseline)",
    "3. **Graph RL** - Graph Convolutional Reinforcement Learning for mesh routing",
    "4. **H-MARL** - Hierarchical Multi-Agent Reinforcement Learning",
    "5. **GAT-RA** - Graph Attention Network Resource Allocation",
    "6. **FedMARL** - Federated Multi-Agent Reinforcement Learning",
    "7. **Intent-Based Networking (IBN)** - Traditional Centralized SDN Intent Translation",
    "8. **Knowledge Graph Networking** - Static Ontology/KG-guided routing",
    "9. **AI-Native Network Orchestration** - Cloud-centric predictive resource allocation",
    "10. **Semantic Communication Framework** - Task-oriented semantic compression only",
    "",
    "---",
    ""
]

for folder, cat_title in categories:
    folder_path = os.path.join(base_dir, folder)
    if not os.path.exists(folder_path):
        continue
    files = sorted([f for f in os.listdir(folder_path) if f.endswith(".png")])
    lines.append(f"## {cat_title}")
    lines.append("")
    for f in files:
        parts = f.replace(".png", "").split("_", 1)
        num = parts[0]
        name = parts[1].replace("_", " ") if len(parts) > 1 else f
        abs_path = f"d:/ff/evaluation_graphs_all_77/{folder}/{f}"
        lines.append(f"- **Figure {num}:** [{name}](file:///{abs_path})")
    lines.append("")
    lines.append("---")
    lines.append("")

lines.extend([
    "## Calibration & Ground Truth Sources",
    "All curves are calibrated against empirical simulation results stored in `results/*.csv`:",
    "- `results/evaluation_report.csv` - Baseline delay, throughput, and PDR anchors",
    "- `results/scalability_comparison.csv` - Constellation scale curves (20-200 nodes)",
    "- `results/convergence.csv` - Multi-agent training convergence histories",
    "- `results/link_failure.csv` - Robustness under physical ISL severance",
    "- `results/congestion.csv` - Buffer stress and traffic density scaling",
    "- `results/intent_comparison.csv` - Mission-specific KPI profiles",
    "- `results/ablation.csv` - Component contribution and cognitive sharing ablation",
    "",
    "*Generated by `plot_evaluation_graphs.py` with reproducible deterministic seed anchoring.*"
])

doc_path = r"d:\ff\Evaluation_Graphs_List.md"
with open(doc_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print("Evaluation_Graphs_List.md updated successfully!")
